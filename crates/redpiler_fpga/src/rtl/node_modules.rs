use super::inputs::Inputs;
use super::instance::Instance;
use crate::circuit::{Circuit, ComparatorMode, Kind, Link, PULSE_PRIORITY};
use crate::registers::Registers;

pub(super) struct NodeModules<'a> {
    circuit: &'a Circuit,
    registers: &'a Registers<'a>,
    inputs: Inputs<'a>,
    index_width: u32,
}

impl<'a> NodeModules<'a> {
    pub(super) fn new(registers: &'a Registers<'a>) -> Self {
        let circuit = registers.circuit;
        Self {
            circuit,
            registers,
            inputs: Inputs::new(registers),
            index_width: (usize::BITS - (circuit.nodes().len() - 1).leading_zeros()).max(1),
        }
    }

    pub(super) fn instance(&self, index: usize) -> Option<Instance> {
        let node = &self.circuit.nodes()[index];
        let initial = node.initial;
        let module = match node.kind {
            Kind::Constant => return None,
            Kind::Lever | Kind::PressurePlate => "node_switch",
            Kind::Button => "node_button",
            Kind::Torch => "node_torch",
            Kind::Repeater { .. } => "node_repeater",
            Kind::Comparator { .. } => "node_comparator",
            Kind::Lamp => "node_lamp",
            Kind::Trapdoor => "node_trapdoor",
            Kind::Wire => "node_wire",
        };
        let mut instance = Instance::new(module, index);
        if let Kind::Repeater {
            delay,
            facing_diode,
        } = node.kind
        {
            instance.parameter("DELAY", delay);
            instance.parameter("FACING_DIODE", facing_diode);
        }
        if let Kind::Comparator {
            mode,
            far_input,
            facing_diode,
        } = node.kind
        {
            instance.parameter("SUBTRACT", mode == ComparatorMode::Subtract);
            if let Some(far_input) = far_input {
                instance.parameter("HAS_FAR_INPUT", true);
                instance.parameter("FAR_INPUT", far_input);
            }
            instance.parameter("FACING_DIODE", facing_diode);
            if let Some((low, high)) = self.registers.two_level(index) {
                instance.parameter("TWO_LEVEL", true);
                instance.parameter("LOW", low);
                instance.parameter("HIGH", high);
            }
            instance.parameter("STRENGTH", initial.strength);
            instance.parameter("PREVIOUS_DESIRED", self.initial_desired(index));
        } else if node.kind == Kind::Wire {
            instance.parameter("STRENGTH", initial.strength);
        } else {
            instance.parameter("POWERED", initial.is_powered());
        }
        if matches!(node.kind, Kind::Torch | Kind::Repeater { .. } | Kind::Lamp) {
            instance.parameter("PREVIOUS_INPUT", self.initial_strength(&node.inputs) != 0);
        }
        if self.registers.is_lockable(index) {
            instance.parameter("LOCKABLE", true);
            instance.parameter("LOCKED", initial.locked);
        }
        if node.kind.has_pulse_countdown() && initial.priority == PULSE_PRIORITY {
            instance.parameter("PENDING_PULSE", initial.delay);
        } else {
            instance.parameter("PENDING", initial.delay);
        }
        if matches!(node.kind, Kind::Lever | Kind::PressurePlate | Kind::Button) {
            instance.parameter("INDEX", index as u32);
            instance.parameter("INDEX_WIDTH", self.index_width);
        }
        self.connect_inputs(index, &mut instance);
        Some(instance)
    }

    fn connect_inputs(&self, index: usize, instance: &mut Instance) {
        let node = &self.circuit.nodes()[index];
        instance.port("clock", "clock");
        if node.kind.is_timed() {
            instance.port("begin_tick", "begin_tick");
            instance.port("firing", "firing");
        }
        match node.kind {
            Kind::Lever | Kind::PressurePlate | Kind::Button => {
                instance.port("input_nodes", "input_nodes");
                instance.port("input_index", "input_index");
                instance.port("input_value", "input_value");
            }
            Kind::Comparator { .. } => {
                instance.port("input_strength", self.inputs.strength(&node.inputs));
                instance.port("side_strength", self.inputs.strength(&node.sides));
            }
            Kind::Wire => instance.port("input_strength", self.inputs.strength(&node.inputs)),
            Kind::Repeater { .. } => {
                instance.port("input_power", self.inputs.power(&node.inputs));
                instance.port("side_power", self.inputs.power(&node.sides));
            }
            Kind::Torch | Kind::Lamp | Kind::Trapdoor => {
                instance.port("input_power", self.inputs.power(&node.inputs));
            }
            Kind::Constant => {}
        }
    }

    fn initial_strength(&self, links: &[Link]) -> u8 {
        links
            .iter()
            .map(|link| {
                self.circuit.nodes()[link.source]
                    .initial
                    .strength
                    .saturating_sub(link.attenuation)
            })
            .max()
            .unwrap_or(0)
    }

    fn initial_desired(&self, index: usize) -> u8 {
        let node = &self.circuit.nodes()[index];
        let Kind::Comparator {
            mode, far_input, ..
        } = node.kind
        else {
            unreachable!("only comparators have a desired strength");
        };
        let main = self.initial_strength(&node.inputs);
        let rear = match far_input {
            Some(far) if main < 15 => far,
            _ => main,
        };
        let side = self.initial_strength(&node.sides);
        if rear < side {
            0
        } else if mode == ComparatorMode::Subtract {
            rear - side
        } else {
            rear
        }
    }
}
